def list_catalog_presets(search_query: str | None = None, include_advanced: bool = True) -> list[dict[str, Any]]:
    items = list(GEE_PRESET_CATALOG.values())
    if not include_advanced:
        items = [it for it in items if it["level"] != "lanjut"]
    if search_query and search_query.strip():
        q = search_query.strip().lower()
        filtered = []
        for it in items:
            haystack = " ".join([
                it["name"],
                it["technical_name"],
                it["description"],
                it["use_case"],
                " ".join(it.get("keywords", [])),
            ]).lower()
            if q in haystack:
                filtered.append(it)
        return filtered
    return items


def get_preset(preset_id: str) -> dict[str, Any]:
    if preset_id in GEE_PRESET_CATALOG:
        return GEE_PRESET_CATALOG[preset_id]
    raise KeyError(f"Preset Katalog Bumi '{preset_id}' tidak ditemukan.")
